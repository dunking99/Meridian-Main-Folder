export type Kind =
  | "equity"
  | "etf"
  | "bond_etf"
  | "reit_etf"
  | "commodity_etf"
  | "cash";

export interface InstrumentSeed {
  symbol: string;
  name: string;
  kind: Kind;
  exchange: string;
  currency: string;
  country: string; // ISO-3166 alpha-2
  region: string;
  sector: string;
  industry: string;
  assetClass: "Equity" | "Fixed Income" | "Alternatives" | "Cash";
  style: "Growth" | "Blend" | "Value";
  marketCap: number; // USD bn (0 = n/a)
  pe: number;
  pb: number;
  divYield: number; // %
  expenseRatio: number; // %
  /** last close, in the instrument's own trading currency */
  last: number;
  /** annualised volatility used by the price generator */
  vol: number; // %
  /** annualised drift used by the price generator */
  drift: number; // %
  /** beta to the global equity factor */
  beta: number;
  sectorFactor: string;
  summary: string;
}

